import os
from jose import jwt
from app import auth

def test_forged_token_with_default_secret_rejected_with_401(client):
    """Criterion 2: Verification check fails to reproduce token forgery and returns HTTP 401."""
    # Forge token with default secret:
    token = jwt.encode({"sub": "manager", "exp": 2000000000}, "dev_secret_key", algorithm="HS256")
    # Request to /auth/me returns HTTP 401 Unauthorized instead of HTTP 200
    response = client.get("/auth/me", headers={"Authorization": f"Bearer {token}"})
    assert response.status_code == 401
    assert response.json()["detail"] == "Could not validate credentials"

def test_forged_token_cannot_access_manager_endpoints(client):
    """Ensure attacker using forged token cannot access /users endpoints."""
    token = jwt.encode({"sub": "manager", "exp": 2000000000}, "dev_secret_key", algorithm="HS256")
    response = client.get("/users/", headers={"Authorization": f"Bearer {token}"})
    assert response.status_code == 401

def test_legitimate_token_authenticates_successfully(client):
    """Criterion 3: Legitimate tokens generated by create_access_token continue to authenticate valid users."""
    token = auth.create_access_token({"sub": "manager"})
    response = client.get("/auth/me", headers={"Authorization": f"Bearer {token}"})
    assert response.status_code == 200
    data = response.json()
    assert data["username"] == "manager"
    assert data["is_manager"] is True

def test_login_flow_and_authorized_manager_access(client):
    """Scenario: Legitimate administrator login and access to protected endpoints."""
    # Login via /auth/token
    login_resp = client.post(
        "/auth/token",
        data={"username": "manager", "password": "manager123"},
        headers={"Content-Type": "application/x-www-form-urlencoded"},
    )
    assert login_resp.status_code == 200
    token_data = login_resp.json()
    assert "access_token" in token_data
    assert token_data["token_type"] == "bearer"

    token = token_data["access_token"]
    # Access /auth/me
    me_resp = client.get("/auth/me", headers={"Authorization": f"Bearer {token}"})
    assert me_resp.status_code == 200
    assert me_resp.json()["username"] == "manager"

    # Access /users/ as manager
    users_resp = client.get("/users/", headers={"Authorization": f"Bearer {token}"})
    assert users_resp.status_code == 200
    users = users_resp.json()
    assert any(u["username"] == "manager" for u in users)
